export function dotLayout(text: string, pitchX = 5, pitchY = 4, gap = 1) {
  const dots: [number, number][] = []
  let x = 0
  for (const ch of text) {
    const rows = (G[ch] ?? G[ch.toLowerCase()] ?? G[' ']).split(' ')
    const cols = rows[0].length
    rows.forEach((row, y) => [...row].forEach((bit, col) => { if (bit === '1') dots.push([x + col * pitchX + 1.55, y * pitchY + 1.55]) }))
    x += (cols + gap) * pitchX
  }
  return { dots, width: x }
}

interface Props {
  text: string
  /** 4 for headline words, 5 for metric numbers */
  pitchX?: number
  radius?: number
  className?: string
  style?: React.CSSProperties
  /** Height of the lettering; width follows the glyph aspect ratio */
  height?: string
}

export default function DotText({ text, pitchX = 5, radius = 1.55, className = '', style, height }: Props) {
  const { dots, width } = dotLayout(text, pitchX)
  return (
    <svg
      className={`dot-svg ${className}`}
      viewBox={`0 0 ${width} 28`}
      role="img"
      aria-label={text}
      style={height ? { height, width: `calc(${height} * ${width / 28})`, ...style } : style}
    >
      {dots.map(([cx, cy], i) => <circle key={i} cx={cx} cy={cy} r={radius} fill="currentColor" />)}
    </svg>
  )
}
